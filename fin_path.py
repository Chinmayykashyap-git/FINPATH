# =========================
# FINPATH AI PROJECT
# =========================

import numpy as np
import pandas as pd
import matplotlib.pyplot as plt
import uuid
import random
from sklearn.model_selection import train_test_split
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score

# =========================
# 1. SIMULATED TRANSACTIONS
# =========================

np.random.seed(42)

N = 200000  # simulate high load

def generate_transaction():
    return {
        "finpath_id": str(uuid.uuid4()),
        "time": random.randint(0, 23),
        "user_latency": np.random.normal(50, 10),
        "server_latency": np.random.normal(70, 15),
        "bank_latency": np.random.normal(60, 12),
        "load": random.randint(10000, 25000)
    }

data = pd.DataFrame([generate_transaction() for _ in range(N)])

# =========================
# 2. FAILURE SIMULATION
# =========================

def assign_failure(row):
    prob = 0.02  # base failure rate

    if row["load"] > 20000:
        prob += 0.03

    if row["server_latency"] > 90:
        prob += 0.04

    if row["bank_latency"] > 80:
        prob += 0.05

    return np.random.choice([0, 1], p=[prob, 1-prob])

data["success"] = data.apply(assign_failure, axis=1)

# =========================
# 3. FAILURE NODE LABEL
# =========================

def failure_node(row):
    if row["success"] == 1:
        return "None"

    latencies = {
        "User": row["user_latency"],
        "Server": row["server_latency"],
        "Bank": row["bank_latency"]
    }

    return max(latencies, key=latencies.get)

data["failed_node"] = data.apply(failure_node, axis=1)

# =========================
# 4. MODEL 1 (SUCCESS PREDICTOR)
# =========================

features = ["time", "user_latency", "server_latency", "bank_latency", "load"]

X = data[features]
y = data["success"]

X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2)

model1 = RandomForestClassifier(n_estimators=100)
model1.fit(X_train, y_train)

y_pred = model1.predict(X_test)
accuracy = accuracy_score(y_test, y_pred)

# =========================
# 5. MODEL 2 (FAILURE ANALYZER)
# =========================

fail_data = data[data["success"] == 0]

X2 = fail_data[features]
y2 = fail_data["failed_node"]

X2_train, X2_test, y2_train, y2_test = train_test_split(X2, y2, test_size=0.2)

model2 = RandomForestClassifier(n_estimators=100)
model2.fit(X2_train, y2_train)

y2_pred = model2.predict(X2_test)
accuracy2 = accuracy_score(y2_test, y2_pred)

# =========================
# BLOCK 1: RESULTS
# =========================

print("==== BLOCK 1: MODEL PERFORMANCE ====")
print("Transaction Success Model Accuracy:", accuracy)
print("Failure Analyzer Model Accuracy:", accuracy2)

# Graph: Success vs Failure
plt.figure()
data["success"].value_counts().plot(kind='bar')
plt.title("Transaction Success vs Failure")
plt.xticks([0,1], ["Failure", "Success"])
plt.show()

# =========================
# BLOCK 2: BANK INSIGHTS
# =========================

print("\n==== BLOCK 2: BANK INSIGHTS ====")

# Most failing node
node_fail_counts = fail_data["failed_node"].value_counts()
print("\nMost Problematic Node:")
print(node_fail_counts)

# Peak failure time
time_fail = fail_data["time"].value_counts().sort_index()

peak_time = time_fail.idxmax()
print("\nPeak Failure Hour:", peak_time)

# Plot failure by time
plt.figure()
time_fail.plot()
plt.title("Failures by Hour")
plt.xlabel("Hour")
plt.ylabel("Failures")
plt.show()

# Summary insights
print("\n--- INSIGHTS ---")
print(f"Most failures occur at hour: {peak_time}")
print(f"Highest failing node: {node_fail_counts.idxmax()}")
print("Recommendation: Avoid high-value transactions during peak failure time.")